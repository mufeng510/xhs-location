# 未识别 / 境外节点回退位置（北京），与 App 默认行为一致
FALLBACK = ("其他地区", "北京", 39.9042, 116.4074)


def classify_province(region_text: str | None) -> tuple[str, str, float, float]:
    """把归属地字符串归一化为 (省份, 省会城市, 纬度, 经度)。

    region_text 形如 "中国|浙江省|杭州市|电信|CN" 或 "浙江 杭州 电信" 等，
    提取其中能匹配到的省级关键词；匹配不到返回 FALLBACK。
    """
    text = (region_text or "").replace("|", " ")
    if not text.strip():
        return FALLBACK
    # 先整体匹配港澳台等特殊写法
    for name, city, lat, lon, keywords in _PROVINCES:
        for kw in keywords:
            if kw in text:
                return (name, city, lat, lon)
    return FALLBACK


def all_provinces() -> list[tuple[str, str, float, float]]:
    """全部省级区域 (name, 省会, lat, lon)，供 admin 页分组顺序使用。"""
    return [(name, city, lat, lon) for name, city, lat, lon, _ in _PROVINCES]
